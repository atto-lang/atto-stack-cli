#![forbid(unsafe_code)]

//! Host-side filesystem/CLI adapter for native Oreslang route, page, RPC and
//! Lambda source modules. Never an Oreslang parser, compiler or FaaS runtime.
use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

pub const GENERATED: &str = "// @generated by oreslang-stack-cli; DO NOT EDIT.\n";
const SCHEMA: &str = "oreslang.stack.inventory/v1";

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Role {
    Api,
    AdminApi,
    Web,
    AdminWeb,
}
impl Role {
    fn parse(value: &str) -> Result<Self, String> {
        match value {
            "api" => Ok(Self::Api),
            "admin-api" => Ok(Self::AdminApi),
            "web" => Ok(Self::Web),
            "admin-web" => Ok(Self::AdminWeb),
            _ => Err(format!("invalid repository role {value:?}; expected api|admin-api|web|admin-web")),
        }
    }
    fn is_api(self) -> bool {
        matches!(self, Self::Api | Self::AdminApi)
    }
    fn as_str(self) -> &'static str {
        match self {
            Self::Api => "api",
            Self::AdminApi => "admin-api",
            Self::Web => "web",
            Self::AdminWeb => "admin-web",
        }
    }
}

#[derive(Clone, Debug)]
struct Operation {
    method: String,
    route: String,
    symbol: String,
}
#[derive(Clone, Debug)]
struct Leaf {
    source: PathBuf,
    relative: String,
    route: String,
    operations: Vec<Operation>,
    page_symbol: Option<String>,
}
#[derive(Clone, Debug)]
struct Inventory {
    role: Role,
    leaves: Vec<Leaf>,
}
#[derive(Clone, Debug)]
struct Config {
    root: PathBuf,
    check: bool,
    role: Option<Role>,
    compiler: String,
}

fn options(args: &[String]) -> Result<Config, String> {
    let mut root = PathBuf::from(".");
    let mut root_seen = false;
    let mut check = false;
    let mut role = None;
    let mut compiler = std::env::var("ORESLANG_COMPILER").unwrap_or_else(|_| "oreslang".into());
    let mut it = args.iter();
    while let Some(arg) = it.next() {
        match arg.as_str() {
            "--root" => {
                if root_seen { return Err("--root may occur only once".into()); }
                root = PathBuf::from(it.next().ok_or("--root needs a directory")?);
                root_seen = true;
            }
            "--check" => {
                if check { return Err("--check specified twice".into()); }
                check = true;
            }
            "--role" => {
                if role.is_some() { return Err("--role specified twice".into()); }
                role = Some(Role::parse(it.next().ok_or("--role needs a role")?)?);
            }
            "--compiler" => compiler = it.next().ok_or("--compiler needs an executable")?.to_owned(),
            _ => return Err(format!("unknown option {arg:?}")),
        }
    }
    if root.as_os_str().is_empty() || compiler.is_empty() {
        return Err("empty root or compiler".into());
    }
    Ok(Config { root, check, role, compiler })
}

pub fn execute(args: &[String]) -> Result<String, String> {
    let (command, tail) = args.split_first().ok_or_else(help)?;
    match command.as_str() {
        "--help" | "-h" | "help" => Ok(help()),
        "--version" | "version" => Ok(env!("CARGO_PKG_VERSION").into()),
        "init" => {
            let opt = options(tail)?;
            if opt.check { return Err("init does not support --check".into()); }
            create_project(&opt)
        }
        "inspect" | "routes" => {
            let opt = options(tail)?;
            if opt.role.is_some() || opt.check { return Err("inspect accepts neither --role nor --check".into()); }
            let inv = discover(&opt.root)?;
            Ok(manifest(&inv))
        }
        "generate" => {
            let (kind, more) = tail.split_first().ok_or("generate needs rpc|lambda|all")?;
            if !matches!(kind.as_str(), "rpc" | "lambda" | "all") {
                return Err("generate needs rpc|lambda|all".into());
            }
            let opt = options(more)?;
            if opt.role.is_some() { return Err("generate does not accept --role".into()); }
            generate(&opt.root, kind, opt.check)
        }
        "check" => {
            let opt = options(tail)?;
            if opt.role.is_some() || opt.check { return Err("check accepts neither --role nor --check".into()); }
            compiler_check(&opt.root, &opt.compiler)
        }
        "plan" => plan(tail),
        "dev" | "build" | "deploy" => Err(format!(
            "{command} requires an admitted Oreslang compiler/runtime and deployment adapter; no stub success is permitted"
        )),
        _ => Err(format!("unknown command {command:?}\n{}", help())),
    }
}

fn help() -> String {
    "Usage: oreslang-stack init --role api|admin-api|web|admin-web [--root DIR]\n  oreslang-stack inspect|routes [--root DIR]\n  oreslang-stack generate rpc|lambda|all [--root DIR] [--check]\n  oreslang-stack check [--root DIR] [--compiler EXEC]\n  oreslang-stack plan --target TARGET [--root DIR]\n  oreslang-stack version\n\nGeneration is source-level only. Build/deploy require a real runtime adapter.".into()
}

/// A truthful, non-deployable target plan; never an execution receipt.
fn plan(args: &[String]) -> Result<String, String> {
    let (flag, more) = args.split_first().ok_or("plan requires --target STACK")?;
    if flag != "--target" { return Err("plan requires --target STACK".into()); }
    let (target, more) = more.split_first().ok_or("plan requires a target name")?;
    let opt = options(more)?;
    if opt.role.is_some() || opt.check { return Err("plan does not accept --role or --check".into()); }
    let inv = discover(&opt.root)?;
    // Never represent a dirty or missing generated artifact as deployable.
    generate(&opt.root, "all", true)?;
    let (admission, artifact, reason) = match target.as_str() {
        "oreslang-stack" => ("planned", "oreslang-native", "native Oreslang compiler/runtime adapter not admitted"),
        "scintilla-run" => ("planned", "oreslang-runtime-adapter", "Scintilla polyglot adapter not admitted"),
        "wasm-xprs" => ("future-backend", "wasm", "Oreslang-to-WASM compiler and host adapter not implemented"),
        "iso-lattes" => ("future-backend", "js-or-wasm", "Oreslang-to-JS/WASM compiler and isolate adapter not implemented"),
        "lunatic-lorry" => ("future-backend", "wasm", "Oreslang-to-WASM compiler and actor host adapter not implemented"),
        "beamscale" => return Err("unsupported deployment target beamscale: Oreslang will not compile to Erlang/BEAM".into()),
        "pony-expres" => return Err("unsupported deployment target pony-expres: Oreslang will not compile to Pony".into()),
        "ores-stack" | "graal-show" | "litegraph" =>
            return Err(format!("unsupported Oreslang deployment target {target}: no admitted source/backend/host adapter")),
        _ => return Err(format!("unsupported Oreslang deployment target {target:?}")),
    };
    Ok(format!(
        "{{\n  \"schema\": \"oreslang.stack.deploy-plan/v1\",\n  \"source_language\": \"oreslang\",\n  \"target\": {},\n  \"repository_role\": {},\n  \"status\": {},\n  \"required_artifact\": {},\n  \"deployable\": false,\n  \"reason\": {}\n}}",
        json_string(target), json_string(inv.role.as_str()), json_string(admission),
        json_string(artifact), json_string(reason)
    ))
}

fn create_project(opt: &Config) -> Result<String, String> {
    let role = opt.role.ok_or("init requires explicit --role")?;
    let root = &opt.root;
    if root.exists() && !root.is_dir() { return Err("root is not a directory".into()); }
    fs::create_dir_all(root).map_err(|e| format!("create root: {e}"))?;
    let config = root.join("oreslang-stack.toml");
    if config.exists() { return Err("project already initialized".into()); }
    let folder = if role.is_api() { "routes" } else { "pages" };
    let target = root.join("src").join(folder);
    if target.exists() { return Err("refusing init into existing source directory".into()); }
    fs::create_dir_all(&target).map_err(|e| format!("create source: {e}"))?;
    let template = if role.is_api() {
        vec![
            ("handlers.ores", "pub fnc hello(String request) -> String {\n  return request;\n}\n"),
            ("route.ores", "// @ores-route GET / hello\nimport module handlers from \"./handlers\";\n\npub fnc hello(String request) -> String {\n  return handlers.hello(request);\n}\n"),
        ]
    } else {
        vec![("page.ores", "// @ores-page / render\npub fnc render(String request) -> String {\n  return \"<main>Oreslang</main>\";\n}\n")]
    };
    for (name, value) in template { fs::write(target.join(name), value).map_err(|e| e.to_string())?; }
    fs::write(&config, format!("[repository]\nrole = \"{}\"\n", role.as_str())).map_err(|e| e.to_string())?;
    Ok(format!("initialized {} in {}", role.as_str(), root.display()))
}

fn load_role(root: &Path) -> Result<Role, String> {
    let path = root.join("oreslang-stack.toml");
    if fs::symlink_metadata(&path).map_err(|e| format!("{}: {e}", path.display()))?.file_type().is_symlink() {
        return Err("project manifest may not be a symlink".into());
    }
    let value = fs::read_to_string(path).map_err(|e| e.to_string())?;
    let mut section = "";
    let mut found = None;
    for raw in value.lines() {
        let line = raw.trim();
        if line.is_empty() || line.starts_with('#') { continue; }
        if line.starts_with('[') {
            if line != "[repository]" { return Err("unsupported manifest section".into()); }
            section = "repository";
            continue;
        }
        let (key, val) = line.split_once('=').ok_or("malformed oreslang-stack.toml entry")?;
        if section != "repository" || key.trim() != "role" || found.is_some() {
            return Err("only one [repository] role is supported".into());
        }
        let val = val.trim();
        let inner = val.strip_prefix('"').and_then(|s| s.strip_suffix('"'))
            .ok_or("role must be a quoted string")?;
        found = Some(Role::parse(inner)?);
    }
    found.ok_or("missing [repository] role".into())
}

fn ascii_ident(s: &str) -> bool {
    let mut chars = s.bytes();
    matches!(chars.next(), Some(b'a'..=b'z' | b'A'..=b'Z' | b'_'))
        && chars.all(|c| c.is_ascii_alphanumeric() || c == b'_')
}

fn route_for(root: &Path, parent: &Path) -> Result<String, String> {
    let relative = parent.strip_prefix(root).map_err(|e| e.to_string())?;
    let mut parts = Vec::new();
    for part in relative.components() {
        let word = part.as_os_str().to_str().ok_or("non-UTF8 route path")?;
        if let Some(param) = word.strip_prefix('[').and_then(|s| s.strip_suffix(']')) {
            if !ascii_ident(param) { return Err(format!("invalid dynamic route segment {word}")); }
            parts.push(format!("{{{param}}}"));
        } else if !word.is_empty() && word.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_') {
            parts.push(word.to_owned());
        } else { return Err(format!("unsupported route path segment {word:?}")); }
    }
    Ok(if parts.is_empty() { "/".into() } else { format!("/{}", parts.join("/")) })
}

fn collect_files(dir: &Path, all: &mut Vec<PathBuf>, depth: usize) -> Result<(), String> {
    if !dir.exists() { return Ok(()); }
    if depth > 32 { return Err(format!("route depth exceeds 32: {}", dir.display())); }
    let meta = fs::symlink_metadata(dir).map_err(|e| e.to_string())?;
    if meta.file_type().is_symlink() { return Err(format!("symlink directory refused: {}", dir.display())); }
    if !meta.is_dir() { return Err(format!("expected directory: {}", dir.display())); }
    for entry in fs::read_dir(dir).map_err(|e| e.to_string())? {
        let path = entry.map_err(|e| e.to_string())?.path();
        let meta = fs::symlink_metadata(&path).map_err(|e| e.to_string())?;
        if meta.file_type().is_symlink() { return Err(format!("symlink refused: {}", path.display())); }
        if meta.is_dir() { collect_files(&path, all, depth + 1)?; }
        else if meta.is_file() { all.push(path); }
    }
    all.sort();
    Ok(())
}

fn signature(source: &str, symbol: &str) -> bool {
    // Source-shape check only; the Oreslang compiler is the semantic authority.
    source.lines().any(|s| {
        let s = s.trim();
        s.starts_with(&format!("pub fnc {symbol}(String request) -> String"))
            || s.starts_with(&format!("pub fnc {symbol}(String request): String"))
    })
}

fn parse_leaf(source_path: &Path, root: &Path, api: bool) -> Result<Leaf, String> {
    let folder = source_path.parent().ok_or("source missing parent")?;
    let route = route_for(root, folder)?;
    let source = fs::read_to_string(source_path).map_err(|e| e.to_string())?;
    let rel = source_path.strip_prefix(root.parent().ok_or("missing root parent")?)
        .unwrap_or(source_path).to_string_lossy().replace('\\', "/");
    let mut operations = Vec::new();
    let mut page_symbol = None;
    let handlers = if api {
        let path = folder.join("handlers.ores");
        if fs::symlink_metadata(&path).map_err(|_| format!("{} requires sibling handlers.ores", source_path.display()))?.file_type().is_symlink() {
            return Err("symlink handlers.ores refused".into());
        }
        fs::read_to_string(path).map_err(|e| e.to_string())?
    } else { String::new() };
    for line in source.lines() {
        let trimmed = line.trim();
        if trimmed.starts_with("// @ores-route") {
            if !api { return Err("web pages cannot declare API routes".into()); }
            let fields: Vec<_> = trimmed.split_whitespace().collect();
            if fields.len() != 5 || fields[0] != "//" || fields[1] != "@ores-route" {
                return Err(format!("invalid @ores-route in {}", source_path.display()));
            }
            let (method, uri, symbol) = (fields[2], fields[3], fields[4]);
            if !matches!(method, "GET" | "POST" | "PUT" | "PATCH" | "DELETE" | "HEAD" | "OPTIONS")
                || uri != route || !ascii_ident(symbol) {
                return Err(format!("invalid method/path/handler in {}: {trimmed}", source_path.display()));
            }
            if !signature(&handlers, symbol) || !signature(&source, symbol) ||
                !source.contains(&format!("handlers.{symbol}(request)")) {
                return Err(format!("route {symbol} must be a public String -> String forwarder to sibling handlers.ores"));
            }
            operations.push(Operation { method: method.into(), route: route.clone(), symbol: symbol.into() });
        } else if trimmed.starts_with("// @ores-page") {
            if api { return Err("API routes cannot declare pages".into()); }
            let fields: Vec<_> = trimmed.split_whitespace().collect();
            if fields.len() != 4 || fields[0] != "//" || fields[1] != "@ores-page" ||
                fields[2] != route || !ascii_ident(fields[3]) || page_symbol.is_some() {
                return Err(format!("invalid or duplicate @ores-page in {}", source_path.display()));
            }
            if !signature(&source, fields[3]) {
                return Err(format!("page renderer {} must be a public String -> String function", fields[3]));
            }
            page_symbol = Some(fields[3].into());
        }
    }
    if api && operations.is_empty() { return Err(format!("{} has no @ores-route directives", source_path.display())); }
    if !api && page_symbol.is_none() { return Err(format!("{} has no @ores-page directive", source_path.display())); }
    let mut seen = BTreeSet::new();
    for op in &operations {
        if !seen.insert((&op.method, &op.symbol)) { return Err("duplicate method/handler in route.ores".into()); }
    }
    Ok(Leaf { source: source_path.into(), relative: rel, route, operations, page_symbol })
}

fn discover(root: &Path) -> Result<Inventory, String> {
    let root = root.canonicalize().map_err(|e| format!("project root {}: {e}", root.display()))?;
    let role = load_role(&root)?;
    let folder = if role.is_api() { "routes" } else { "pages" };
    let source_root = root.join("src").join(folder);
    let mut all = Vec::new();
    collect_files(&source_root, &mut all, 0)?;
    let wanted = if role.is_api() { "route.ores" } else { "page.ores" };
    let mut leaves = Vec::new();
    for p in all.iter().filter(|p| p.file_name().and_then(|s| s.to_str()) == Some(wanted)) {
        leaves.push(parse_leaf(p, &source_root, role.is_api())?);
    }
    if leaves.is_empty() { return Err(format!("no {wanted} in {}", source_root.display())); }
    let mut shapes = BTreeSet::new();
    let mut seen_methods = BTreeSet::new();
    for leaf in &leaves {
        // Different parameter names at the same position still describe one shape.
        let shape = leaf.route.split('/').map(|s| if s.starts_with('{') { "{}" } else { s }).collect::<Vec<_>>().join("/");
        if !shapes.insert(shape) { return Err("ambiguous duplicate path shape".into()); }
        for op in &leaf.operations {
            if !seen_methods.insert((op.method.clone(), op.route.clone())) {
                return Err("duplicate HTTP method and path".into());
            }
        }
        let mut exported = BTreeSet::new();
        for op in &leaf.operations {
            if !exported.insert(&op.symbol) {
                return Err("multiple HTTP methods cannot share a generated export symbol; use one adapter per method".into());
            }
        }
    }
    Ok(Inventory { role, leaves })
}

fn json_string(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if c <= '\u{001f}' => out.push_str(&format!("\\u{:04x}", c as u32)),
            _ => out.push(c),
        }
    }
    out.push('"');
    out
}

fn manifest(inv: &Inventory) -> String {
    let mut out = format!("{{\n  \"schema\": {},\n  \"role\": {},\n  \"entries\": [\n", json_string(SCHEMA), json_string(inv.role.as_str()));
    let mut lines = Vec::new();
    for leaf in &inv.leaves {
        if inv.role.is_api() {
            for op in &leaf.operations {
                lines.push(format!("    {{\"kind\":\"route\",\"method\":{},\"path\":{},\"handler\":{},\"source\":{}}}",
                    json_string(&op.method), json_string(&op.route), json_string(&op.symbol), json_string(&leaf.relative)));
            }
        } else {
            lines.push(format!("    {{\"kind\":\"page\",\"path\":{},\"handler\":{},\"source\":{}}}",
                json_string(&leaf.route), json_string(leaf.page_symbol.as_deref().unwrap_or("")), json_string(&leaf.relative)));
        }
    }
    out.push_str(&lines.join(",\n"));
    out.push_str("\n  ]\n}\n");
    out
}

fn generated_for(inv: &Inventory, kind: &str) -> BTreeMap<PathBuf, String> {
    let mut files = BTreeMap::new();
    for leaf in &inv.leaves {
        let dir = leaf.source.parent().expect("source has parent");
        if inv.role.is_api() {
            if kind != "lambda" {
                let mut src = format!("{GENERATED}// API RPC adapters: transport-neutral String envelope.\nimport module route from \"./route\";\n\n");
                for op in &leaf.operations {
                    src.push_str(&format!("pub fnc rpc_{}(String request) -> String {{\n  return route.{}(request);\n}}\n\n", op.symbol, op.symbol));
                }
                files.insert(dir.join("rpc.ores"), src);
            }
            if kind != "rpc" {
                let mut src = format!("{GENERATED}// Runtime adapter must bind invoke_* exports and implement auth/transport.\nimport module rpc from \"./rpc\";\n\n");
                for op in &leaf.operations {
                    src.push_str(&format!("pub fnc invoke_{}(String request) -> String {{\n  return rpc.rpc_{}(request);\n}}\n\n", op.symbol, op.symbol));
                }
                files.insert(dir.join("lambda.ores"), src);
            }
        } else if kind != "rpc" {
            let sym = leaf.page_symbol.as_deref().expect("page has renderer");
            files.insert(dir.join("lambda.ores"), format!("{GENERATED}// Web page Lambda adapter; host supplies request/response transport.\nimport module page from \"./page\";\n\npub fnc invoke_page(String request) -> String {{\n  return page.{sym}(request);\n}}\n"));
        }
    }
    if kind == "all" {
        let root = inv.leaves[0].source.ancestors()
            .find(|p| p.file_name().and_then(|s| s.to_str()) == Some("src"))
            .and_then(|p| p.parent()).expect("project root");
        files.insert(root.join("generated/route-manifest.json"), manifest(inv));
    }
    files
}

fn sync_one(path: &Path, content: &str, check: bool) -> Result<(), String> {
    let existing = fs::symlink_metadata(path).ok();
    if let Some(meta) = &existing {
        if meta.file_type().is_symlink() || !meta.is_file() {
            return Err(format!("generated output is not a regular file: {}", path.display()));
        }
        let old = fs::read_to_string(path).map_err(|e| e.to_string())?;
        if path.extension().and_then(|s| s.to_str()) == Some("ores") && !old.starts_with(GENERATED) {
            return Err(format!("refusing to overwrite hand-authored source: {}", path.display()));
        }
        if old == content { return Ok(()); }
    }
    if check { return Err(format!("generated output missing/stale: {}", path.display())); }
    let parent = path.parent().ok_or("generated path has no parent")?;
    if !parent.exists() { fs::create_dir_all(parent).map_err(|e| e.to_string())?; }
    let temp = parent.join(format!(".oreslang-stack-{}.tmp", std::process::id()));
    if temp.exists() { return Err("temporary generator file already exists".into()); }
    let result = (|| {
        fs::write(&temp, content).map_err(|e| format!("write generated temporary file: {e}"))?;
        fs::rename(&temp, path).map_err(|e| format!("replace generated artifact: {e}"))
    })();
    if result.is_err() { let _ = fs::remove_file(&temp); }
    result
}

fn generate(root: &Path, kind: &str, check: bool) -> Result<String, String> {
    let inv = discover(root)?;
    if !inv.role.is_api() && kind == "rpc" {
        return Err("web page repositories do not own RPC operations".into());
    }
    if kind == "lambda" && inv.role.is_api() {
        // Lambda imports the generated RPC adapter, so a stale/missing RPC is not allowed.
        let rpc = generated_for(&inv, "rpc");
        for (path, content) in rpc { sync_one(&path, &content, true)?; }
    }
    let wanted = generated_for(&inv, kind);
    let root_path = root.canonicalize().map_err(|e| e.to_string())?;
    // No unchecked symlink traversal is permitted in the source tree.
    let mut existing = Vec::new();
    let folder = if inv.role.is_api() { "routes" } else { "pages" };
    collect_files(&root_path.join("src").join(folder), &mut existing, 0)?;
    let outputs: BTreeSet<_> = wanted.keys().cloned().collect();
    for path in existing {
        let file = path.file_name().and_then(|s| s.to_str());
        if matches!(file, Some("rpc.ores" | "lambda.ores")) &&
            (kind == "all" || (kind == "rpc" && file == Some("rpc.ores")) || (kind == "lambda" && file == Some("lambda.ores"))) &&
            !outputs.contains(&path) {
            let old = fs::read_to_string(&path).map_err(|e| e.to_string())?;
            if !old.starts_with(GENERATED) { return Err(format!("unowned adapter file: {}", path.display())); }
            if check { return Err(format!("orphan generated adapter: {}", path.display())); }
            fs::remove_file(&path).map_err(|e| e.to_string())?;
        }
    }
    for (path, content) in &wanted { sync_one(path, content, check)?; }
    Ok(format!("{} {} generated artifacts {} for {}", wanted.len(), kind,
        if check { "verified" } else { "synchronized" }, inv.role.as_str()))
}

fn compiler_check(root: &Path, compiler: &str) -> Result<String, String> {
    let inv = discover(root)?;
    let _ = generate(root, "all", true)?;
    let mut files = Vec::new();
    let root = root.canonicalize().map_err(|e| e.to_string())?;
    let folder = if inv.role.is_api() { "routes" } else { "pages" };
    collect_files(&root.join("src").join(folder), &mut files, 0)?;
    let sources: Vec<_> = files.into_iter().filter(|p| p.extension().and_then(|e| e.to_str()) == Some("ores")).collect();
    for file in &sources {
        let result = Command::new(compiler).arg("check").arg(file).current_dir(&root).output()
            .map_err(|e| format!("cannot execute Oreslang compiler {compiler:?}: {e}"))?;
        if !result.status.success() {
            return Err(format!("compiler rejected {}: {}{}", file.display(),
                String::from_utf8_lossy(&result.stdout), String::from_utf8_lossy(&result.stderr)));
        }
    }
    Ok(format!("Oreslang compiler checked {} .ores files (compiler: {compiler})", sources.len()))
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::sync::atomic::{AtomicUsize, Ordering};
    static COUNTER: AtomicUsize = AtomicUsize::new(0);
    fn temp() -> PathBuf {
        let path = std::env::temp_dir().join(format!("oreslang-stack-{}-{}", std::process::id(), COUNTER.fetch_add(1, Ordering::SeqCst)));
        fs::create_dir_all(&path).unwrap();
        path
    }
    fn init(root: &Path, role: &str) {
        execute(&["init".into(), "--root".into(), root.display().to_string(), "--role".into(), role.into()]).unwrap();
    }
    fn gen(root: &Path, args: &[&str]) -> Result<String, String> {
        let mut cmd = vec!["generate".into()];
        cmd.extend(args.iter().map(|s| s.to_string()));
        cmd.extend(["--root".into(), root.display().to_string()]);
        execute(&cmd)
    }
    #[test]
    fn api_round_trip_and_drift() {
        let root = temp();
        init(&root, "api");
        assert!(gen(&root, &["all", "--check"]).is_err());
        gen(&root, &["all"]).unwrap();
        gen(&root, &["all", "--check"]).unwrap();
        assert!(fs::read_to_string(root.join("src/routes/rpc.ores")).unwrap().contains("route.hello(request)"));
        assert!(fs::read_to_string(root.join("src/routes/lambda.ores")).unwrap().contains("rpc.rpc_hello(request)"));
        fs::write(root.join("src/routes/rpc.ores"), "user authored").unwrap();
        assert!(gen(&root, &["all"]).unwrap_err().contains("hand-authored"));
        fs::remove_dir_all(root).unwrap();
    }
    #[test]
    fn web_pages_never_become_rpc() {
        let root = temp();
        init(&root, "web");
        assert!(gen(&root, &["rpc"]).unwrap_err().contains("do not own RPC"));
        gen(&root, &["all"]).unwrap();
        assert!(root.join("src/pages/lambda.ores").exists());
        assert!(!root.join("src/pages/rpc.ores").exists());
        gen(&root, &["all", "--check"]).unwrap();
        fs::remove_dir_all(root).unwrap();
    }
    #[test]
    fn nested_routes_and_ambiguous_patterns() {
        let root = temp();
        init(&root, "api");
        let a = root.join("src/routes/users/[id]");
        let b = root.join("src/routes/users/[name]");
        fs::create_dir_all(&a).unwrap();
        fs::create_dir_all(&b).unwrap();
        for (folder, segment) in [(&a, "id"), (&b, "name")] {
            fs::write(folder.join("handlers.ores"), "pub fnc show(String request) -> String { return request; }").unwrap();
            fs::write(folder.join("route.ores"), format!("// @ores-route GET /users/{{{segment}}} show\nimport module handlers from \"./handlers\";\npub fnc show(String request) -> String {{ return handlers.show(request); }}")).unwrap();
        }
        assert!(gen(&root, &["all"]).unwrap_err().contains("ambiguous"));
        fs::remove_dir_all(root).unwrap();
    }
    #[test]
    fn invalid_method_and_role_are_rejected() {
        let root = temp();
        init(&root, "api");
        let path = root.join("src/routes/route.ores");
        fs::write(&path, "// @ores-route TRACE / hello\npub fnc hello(String request) -> String { return request; }").unwrap();
        assert!(gen(&root, &["all"]).unwrap_err().contains("invalid method"));
        fs::write(root.join("oreslang-stack.toml"), "[repository]\nrole = \"not-real\"").unwrap();
        assert!(gen(&root, &["all"]).unwrap_err().contains("invalid repository role"));
        fs::remove_dir_all(root).unwrap();
    }
    #[test]
    fn deployment_allowlist_and_no_false_success() {
        let root = temp();
        init(&root, "api");
        gen(&root, &["all"]).unwrap();
        for target in ["oreslang-stack", "scintilla-run", "wasm-xprs", "iso-lattes", "lunatic-lorry"] {
            let output = execute(&[
                "plan".into(), "--target".into(), target.into(),
                "--root".into(), root.display().to_string()
            ]).unwrap();
            assert!(output.contains("\"deployable\": false"));
            assert!(output.contains(target));
        }
        for target in ["beamscale", "pony-expres", "ores-stack", "graal-show", "litegraph"] {
            let error = execute(&[
                "plan".into(), "--target".into(), target.into(),
                "--root".into(), root.display().to_string()
            ]).unwrap_err();
            assert!(error.contains("unsupported"));
        }
        fs::remove_dir_all(root).unwrap();
    }
    #[test]
    fn no_claim_of_compilation_without_compiler() {
        let root = temp();
        init(&root, "api");
        gen(&root, &["all"]).unwrap();
        let err = execute(&["check".into(), "--root".into(), root.display().to_string(), "--compiler".into(), "definitely-not-an-oreslang-compiler".into()]).unwrap_err();
        assert!(err.contains("cannot execute Oreslang compiler"));
        fs::remove_dir_all(root).unwrap();
    }
    #[test]
    fn unowned_lambda_is_not_overwritten() {
        let root = temp();
        init(&root, "api");
        gen(&root, &["rpc"]).unwrap();
        fs::write(root.join("src/routes/lambda.ores"), "pub fnc anything() -> String { return \"x\"; }").unwrap();
        assert!(gen(&root, &["lambda"]).unwrap_err().contains("hand-authored"));
        fs::remove_dir_all(root).unwrap();
    }
}
